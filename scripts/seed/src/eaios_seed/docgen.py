"""Render `docs/personas.md` and `docs/dataset.md` from the generated dataset.

`docs/README.md` claimed these files were "generated from the live database ... so
they cannot drift into describing records that do not exist". No generator existed.
They drifted: eight of the ten personas named the wrong person, and both files were
stamped with a stale generator version and fingerprint. Nobody noticed for several
convergence passes, because the claim read like a guarantee.

Rendering happens **from the in-process dataset, not from a live database**, which is
a deliberate departure from the original wording. The generator is deterministic
(FR-011), so the two agree by construction — and a docs-freshness check that needs a
running stack is a check that skips itself whenever the stack is down. This project
has already shipped several tests that quietly did exactly that.

Both documents are rendered whole, prose included, so there is no hand-maintained
region that can fall out of step with the generated tables.
"""

